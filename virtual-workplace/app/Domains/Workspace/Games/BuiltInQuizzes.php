    /** One built-in quiz as a playable list of questions, or null. */
    public static function find(string $key): ?array
    {
        $q = self::all()[$key] ?? null;
        if (! $q) {
            return null;
        }

        return [
            'title' => $q['title'],
            'questions' => array_map(fn ($x) => ['q' => $x[0], 'c' => $x[1], 'a' => $x[2], 's' => self::SECONDS], $q['questions']),
        ];
    }
